def total_questions() -> int:
    """中核(必須)質問の数。30問以上を維持する。"""
    return len(required_questions())


def required_questions() -> list[Question]:
    return [q for q in QUESTION_BANK if not q.optional]


def optional_questions() -> list[Question]:
    return [q for q in QUESTION_BANK if q.optional]


def by_category() -> dict[str, list[Question]]:
    grouped: dict[str, list[Question]] = {}
    for q in QUESTION_BANK:
        grouped.setdefault(q.category, []).append(q)
    return grouped
