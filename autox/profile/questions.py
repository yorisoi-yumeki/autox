"""価値観インタビューの質問バンク。

目的: 投稿やDM下書きの「発信内容」が、実際に会ったときの本人の考え方と
乖離しないようにするため、運用開始前に本人の価値観・人柄を言語化しておく。

設計方針(恋愛コンサルタント役・心理学者役のレビューを反映):
- 「大事にしていることは?」のような抽象的な自己評定ではなく、直近の
  具体的なエピソードや場面を思い出してもらう聞き方(行動・エピソード想起)
  を基本にする。抽象的な自己申告より認知負荷が低く、内容も具体的になる。
- 「絶対にしたくないこと/NG」のような断定的・道徳的な言い回しは避け、
  シナリオ提示型に寄せることで社会的望ましさバイアス(建前の回答)を減らす。
- カテゴリの並び順は「事実確認(低負荷)→行動→価値観→重い自己開示→
  未来志向(前向きに終える)」の順にし、短所のような答えにくい質問は
  各カテゴリ内でも最後に置く。
- MBTI/動物占い/ラブキャラ診断/脳波診断のような自己申告の性格ラベルは、それ自体を
  断定に使わず、「〜と言われますが、実際のあなたはどうですか?(当てはまる
  部分も、当てはまらない部分も)」という確認+反証セットの"アイスブレイク"
  としてのみ、関連の深いカテゴリに1問ずつ添える。保存されるのはラベルでは
  なく、そこから本人が語った具体的な内容そのもの。
- 全問必須にはしない。中核(required)の質問群でこれまで通り30問以上を
  維持しつつ、深掘り向けの質問は optional=True にして、答えなくても
  プロフィールとして十分機能するようにする。

各質問は (category, key, text, optional) を持つ。key は
config/profile.yaml に保存する際のフィールド名になる。
"""

